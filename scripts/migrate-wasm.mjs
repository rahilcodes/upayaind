#!/usr/bin/env node
/**
 * Offline migration helper.
 *
 * `prisma migrate` needs a native schema-engine binary that it downloads from
 * binaries.prisma.sh. Some sandboxed environments can't reach that host. This
 * script drives Prisma's official WASM schema engine through the pg driver
 * adapter instead, and reads/writes the normal `prisma/migrations` folder, so
 * its output is identical to `prisma migrate dev` / `deploy`.
 *
 * Usage:
 *   node scripts/migrate-wasm.mjs create <name>   # write a new migration from schema changes
 *   node scripts/migrate-wasm.mjs deploy          # apply pending migrations
 *
 * Wherever the native CLI works (CI, Vercel, your laptop) prefer
 * `pnpm db:migrate` / `pnpm db:deploy`.
 */
import "dotenv/config";
import fs from "node:fs";
import path from "node:path";
import { SchemaEngine } from "@prisma/schema-engine-wasm";
import { PrismaPg } from "@prisma/adapter-pg";
import { bindMigrationAwareSqlAdapterFactory } from "@prisma/driver-adapter-utils";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const schemaPath = path.join(root, "prisma/schema.prisma");
const migrationsDir = path.join(root, "prisma/migrations");
const filters = { externalTables: [], externalEnums: [] };

function loadMigrations() {
  fs.mkdirSync(migrationsDir, { recursive: true });
  const lockPath = path.join(migrationsDir, "migration_lock.toml");
  const dirs = fs
    .readdirSync(migrationsDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
  return {
    baseDir: migrationsDir,
    lockfile: {
      path: "migration_lock.toml",
      content: fs.existsSync(lockPath) ? fs.readFileSync(lockPath, "utf8") : null,
    },
    shadowDbInitScript: "",
    migrationDirectories: dirs.map((name) => {
      const file = path.join(migrationsDir, name, "migration.sql");
      return {
        path: name,
        migrationFile: {
          path: "migration.sql",
          content: fs.existsSync(file)
            ? { tag: "ok", value: fs.readFileSync(file, "utf8") }
            : { tag: "error", value: "missing migration.sql" },
        },
      };
    }),
  };
}

async function engine() {
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error("DATABASE_URL is not set");
  const schema = fs.readFileSync(schemaPath, "utf8");
  const adapter = bindMigrationAwareSqlAdapterFactory(new PrismaPg({ connectionString: url }));
  const eng = await SchemaEngine.new({ datamodels: [["schema.prisma", schema]] }, () => {}, adapter);
  return { eng, schema };
}

const [cmd, name] = process.argv.slice(2);
const { eng, schema } = await engine();

if (cmd === "create") {
  // The WASM engine can't spin up a shadow database through the pg adapter, so
  // we diff the schema against a snapshot of the schema as of the last
  // migration (prisma/.migrate-snapshot.prisma) instead of replaying history.
  if (!name) throw new Error("usage: create <name>");
  const snapPath = path.join(root, "prisma/.migrate-snapshot.prisma");
  const from = fs.existsSync(snapPath)
    ? { tag: "schemaDatamodel", files: [{ path: "schema.prisma", content: fs.readFileSync(snapPath, "utf8") }] }
    : { tag: "empty" };
  const out = await eng.diff({
    from,
    to: { tag: "schemaDatamodel", files: [{ path: "schema.prisma", content: schema }] },
    script: true,
    exitCode: null,
    filters,
  });
  const sql = out.stdout ?? "";
  if (!sql.trim() || /^-- This is an empty migration\.?\s*$/m.test(sql)) {
    console.log("No schema changes.");
  } else {
    const ts = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
    const dir = path.join(migrationsDir, `${ts}_${name.replace(/[^a-z0-9_]/gi, "_")}`);
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(path.join(dir, "migration.sql"), sql);
    fs.writeFileSync(snapPath, schema);
    const lock = path.join(migrationsDir, "migration_lock.toml");
    if (!fs.existsSync(lock)) {
      fs.writeFileSync(
        lock,
        '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
      );
    }
    console.log(`Created ${path.relative(root, dir)}/migration.sql`);
  }
} else if (cmd === "deploy") {
  const out = await eng.applyMigrations({ migrationsList: loadMigrations(), filters });
  console.log(
    out.appliedMigrationNames.length
      ? `Applied: ${out.appliedMigrationNames.join(", ")}`
      : "Database is up to date.",
  );
} else {
  console.log("usage: node scripts/migrate-wasm.mjs <create name|deploy>");
}
process.exit(0);
